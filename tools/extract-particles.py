#!/usr/bin/env python3
"""Turn assets/logo.png into assets/particles.js.

The logo is alpha-cut on a transparent canvas.  We chop it into a square
grid, keep every cell whose alpha coverage is meaningful, and store the cell
index, the quantised colour and the coverage.

The pages picks a sub-grid at runtime (stride 1/2/3...) so the dot pitch
stays constant in screen pixels no matter how large the emblem is drawn.

Output layout is one base64 blob of 4-byte records:

    uint8 gx | uint8 gy | uint8 colour | uint8 coverage

Run:  python tools/extract-particles.py [--step 9] [--preview DIR]
"""

from __future__ import annotations

import argparse
import base64
import json
import pathlib
import struct

import numpy as np
from PIL import Image, ImageDraw

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "logo.png"
OUT = ROOT / "assets" / "particles.js"


# --------------------------------------------------------------------------
# palette: (name, colour in the artwork, colour used on the dark page)
# The dark-theme lift keeps every shape legible on a near-black canvas while
# preserving the hue identity of the original mark.
# --------------------------------------------------------------------------
PALETTE = [
    ("red",    (221, 73, 73),    (228, 82, 80)),
    ("navy",   (6, 50, 143),     (32, 86, 198)),
    ("gold",   (246, 205, 37),   (247, 206, 54)),
    ("ink",    (68, 68, 68),     (92, 98, 108)),
    ("silver", (205, 205, 205),  (232, 235, 239)),
]


def quantise(rgb: np.ndarray) -> np.ndarray:
    """Nearest palette entry, weighted to approximate perceived difference."""
    pal = np.array([c for _, c, _ in PALETTE], dtype=np.float64)
    w = np.array([0.30, 0.59, 0.11])
    diff = (rgb[:, None, :] - pal[None, :, :]) * w
    return np.argmin((diff ** 2).sum(axis=2), axis=1)


def square_crop(arr: np.ndarray) -> np.ndarray:
    alpha = arr[:, :, 3]
    ys, xs = np.where(alpha > 8)
    x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
    side = int(max(x1 - x0, y1 - y0))
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    left, top = int(round(cx - side / 2)), int(round(cy - side / 2))
    out = np.zeros((side, side, 4), dtype=arr.dtype)
    sx0, sy0 = max(0, left), max(0, top)
    sx1, sy1 = min(arr.shape[1], left + side), min(arr.shape[0], top + side)
    out[sy0 - top:sy1 - top, sx0 - left:sx1 - left] = arr[sy0:sy1, sx0:sx1]
    return out


def build(step: int):
    arr = np.asarray(Image.open(SRC).convert("RGBA")).astype(np.float64)
    pad = square_crop(arr)

    grid = pad.shape[0] // step
    assert grid <= 255, "grid too fine for uint8 cell indices"
    cells = pad[: grid * step, : grid * step].reshape(grid, step, grid, step, 4)

    a = cells[..., 3] / 255.0
    cov = a.sum(axis=(1, 3)) / (step * step)
    wsum = a.sum(axis=(1, 3))
    rgb = (cells[..., :3] * a[..., None]).sum(axis=(1, 3))
    rgb = np.divide(rgb, wsum[..., None], out=np.zeros_like(rgb), where=wsum[..., None] > 1e-6)

    keep = cov >= 0.22
    colours = quantise(rgb[keep])
    cover = np.clip(cov[keep], 0, 1)
    gy, gx = np.meshgrid(np.arange(grid), np.arange(grid), indexing="ij")
    gx, gy = gx[keep].astype(int), gy[keep].astype(int)

    records = [
        struct.pack("<BBBB", int(x), int(y), int(c), int(v * 255))
        for x, y, c, v in zip(gx, gy, colours, cover)
    ]

    meta = {
        "version": 2,
        "count": len(records),
        "grid": int(grid),
        "step": int(step),
        "source": int(pad.shape[0]),
        "palette": [[list(src), list(dark)] for _, src, dark in PALETTE],
        "data": base64.b64encode(b"".join(records)).decode("ascii"),
    }
    OUT.write_text(
        "/* generated by tools/extract-particles.py -- do not edit by hand */\n"
        "window.SCNU_PARTICLES = "
        + json.dumps(meta, separators=(",", ":"))
        + ";\n",
        encoding="utf-8",
    )
    print(f"{len(records)} cells, grid {grid}x{grid}, {pad.shape[0]}px square "
          f"-> {OUT.stat().st_size / 1024:.1f} KB")
    return meta, gx, gy, colours, cover


def preview(meta, gx, gy, colours, cover, path: pathlib.Path, dark=True, size=680, stride=1):
    ss = 2
    grid = meta["grid"]
    img = Image.new("RGB", (size * ss, size * ss), (8, 9, 11) if dark else (247, 247, 248))
    d = ImageDraw.Draw(img)
    pal = [c[2] if dark else c[1] for c in PALETTE]
    for x, y, c, v in zip(gx, gy, colours, cover):
        if x % stride or y % stride:
            continue
        px = (x + 0.5) / grid * size * ss
        py = (y + 0.5) / grid * size * ss
        r = (0.55 + 0.75 * min(1, v * 1.35)) * ss * 1.6
        d.ellipse((px - r, py - r, px + r, py + r), fill=pal[int(c)])
    img.save(path)
    print("preview ->", path)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--step", type=int, default=9)
    ap.add_argument("--preview", type=pathlib.Path, default=None,
                    help="also write PNG previews into this directory")
    args = ap.parse_args()
    meta, gx, gy, cs, cv = build(args.step)
    if args.preview:
        args.preview.mkdir(parents=True, exist_ok=True)
        preview(meta, gx, gy, cs, cv, args.preview / "preview-dark.png", dark=True)
        preview(meta, gx, gy, cs, cv, args.preview / "preview-dark-mobile.png", dark=True, size=340, stride=2)
